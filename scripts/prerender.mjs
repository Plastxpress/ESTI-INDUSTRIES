// Writes one static HTML file per route into dist/ so every heading, product text
// and <img> tag is present in the raw HTML (view-source), then React hydrates it.
//
//   /            -> dist/index.html
//   /about       -> dist/about.html       (served at /about by Vercel cleanUrls,
//   /contact     -> dist/contact.html      Netlify pretty URLs and .htaccess)
//   ...
//   not found    -> dist/404.html
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const SSR = path.join(ROOT, 'dist-ssr', 'entry-server.js');

const { render, ROUTES, NOT_FOUND, markdownFor, mdPath, sitemapMd, llmsTxt, PLANT_PHOTOS } = await import(pathToFileURL(SSR).href);
// The pages are fully pre-rendered, so the app script (hydration only) is fetched after the
// page's load event, or at the first interaction, so it doesn't compete with first paint.
const template = fs
  .readFileSync(path.join(DIST, 'index.html'), 'utf8')
  .replace(/<script type="module" crossorigin src="([^"]+)"><\/script>/, (_, src) =>
    `<script type="module">const go=()=>import(${JSON.stringify(src)});addEventListener('load',()=>setTimeout(go,0),{once:true});['pointerdown','keydown','touchstart'].forEach((t)=>addEventListener(t,go,{once:true,passive:true}));</script>`);
if (!/import\("\/assets\/index-/.test(template)) throw new Error('app script tag not found for deferred loading');

if (!template.includes('<!--app-head-->') || !template.includes('<!--app-html-->')) {
  throw new Error('index.html template placeholders missing');
}

const outFile = (p) => (p === '/' ? 'index.html' : `${p.slice(1)}.html`);

for (const route of [...ROUTES, NOT_FOUND]) {
  const { html, head } = render(route.path);
  const page = template.replace('<!--app-head-->', head).replace('<!--app-html-->', html);
  const file = route === NOT_FOUND ? '404.html' : outFile(route.path);
  fs.writeFileSync(path.join(DIST, file), page);
  console.log(`prerendered ${route.path.padEnd(24)} -> dist/${file}  (${(page.length / 1024).toFixed(0)} KB)`);
}

// sitemap.xml — every indexable page (+ product images). Written to dist/ and
// mirrored to public/ so the committed file always matches the live pages.
const SITE = 'https://www.estipack.com';
// lastmod = when site content last changed: the last commit touching site files, or
// today if there are uncommitted changes to them (falls back to today without git).
const today = (() => {
  const now = new Date().toISOString().slice(0, 10);
  try {
    const opts = { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] };
    const paths = '-- src public index.html';
    if (execSync(`git status --porcelain ${paths}`, opts).trim()) return now;
    return execSync(`git log -1 --format=%cs ${paths}`, opts).trim() || now;
  } catch {
    return now;
  }
})();
const xmlEsc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const webpPath = (src) => `/assets/images/webp/${src.replace(/^.*\//, '').replace(/\.(png|jpe?g)$/i, '')}.webp`;
const imageXml = (src, title) =>
  `    <image:image>\n      <image:loc>${SITE}${webpPath(src)}</image:loc>\n      <image:title>${xmlEsc(title)}</image:title>\n    </image:image>`;
const urls = ROUTES.map((r) => {
  let images = '';
  if (r.product) images = r.product.images.map((src, i) => imageXml(src, i === 0 ? r.product.title : r.product.imageLabels[i])).join('\n');
  if (r.path === '/about') images = PLANT_PHOTOS.map((ph) => imageXml(ph.src, `${ph.caption} at the ESTI Packaging plant`)).join('\n');
  return `  <url>\n    <loc>${SITE}${r.path}</loc>\n    <lastmod>${today}</lastmod>\n    <priority>${r.path === '/' ? '1.0' : r.product ? '0.9' : '0.7'}</priority>\n${images ? images + '\n' : ''}  </url>`;
});
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prerender.mjs from src/routes.js — do not edit by hand. -->
<!-- Markdown versions of these pages: https://www.estipack.com/sitemap.md (guide for AI tools: https://www.estipack.com/llms.txt) -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls.join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(DIST, 'sitemap.xml'), sitemap);
fs.writeFileSync(path.join(ROOT, 'public', 'sitemap.xml'), sitemap);
console.log(`sitemap.xml: ${ROUTES.length} URLs`);

// Markdown versions of every page + sitemap.md + llms.txt (same data as the HTML).
let mdCount = 0;
for (const route of ROUTES) {
  const md = markdownFor(route);
  if (!md) continue;
  fs.writeFileSync(path.join(DIST, mdPath(route.path).slice(1)), md);
  mdCount++;
}
fs.writeFileSync(path.join(DIST, 'sitemap.md'), sitemapMd(ROUTES));
fs.writeFileSync(path.join(DIST, 'llms.txt'), llmsTxt(ROUTES));
console.log(`markdown: ${mdCount} pages + sitemap.md + llms.txt`);

fs.rmSync(path.join(ROOT, 'dist-ssr'), { recursive: true, force: true });
